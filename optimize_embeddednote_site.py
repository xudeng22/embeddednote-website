"""EmbeddedNote Astro site performance optimizer. Preview by default; --apply to modify.

Targets: lossless raster image conversion, img dimensions / below-fold lazy loading,
search box layout reservation, safe backups and an HTML review report.
Does not edit AdSense, article text, slugs, SEO metadata, Giscus or Cloudflare settings.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import html
import json
