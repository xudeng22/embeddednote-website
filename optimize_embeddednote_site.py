import shutil
import sys
from pathlib import Path
from urllib.parse import quote

try:
    from PIL import Image, ImageOps
except ImportError:
    print("缺少 Pillow。请运行: py -m pip install --upgrade Pillow", file=sys.stderr)
    sys.exit(2)

IMAGE_EXTS = {".png", ".jpg", ".jpeg"}
SOURCE_EXTS = {".md", ".mdx", ".astro", ".css", ".js", ".ts", ".mjs"}
PLUGIN_REL = Path("scripts/rehype-embeddednote-images.mjs")
MANIFEST_REL = Path("src/data/performance-image-manifest.json")
MARKER = "EmbeddedNote Performance Image Plugin"
IMAGE_PLUGIN = r'''// EmbeddedNote Performance Image Plugin — generated by optimize_embeddednote_site.py
// Applies dimensions to Markdown/HTML images at build time (no runtime JS).
import { readFileSync } from 'node:fs';
const manifest = JSON.parse(readFileSync(new URL('../src/data/performance-image-manifest.json', import.meta.url), 'utf8'));
export default function embeddednoteImages() {
  return function transformer(tree) {
    let imageIndex = 0;
    function visit(node) {
      if (!node || typeof node !== 'object') return;
      if (node.type === 'element' && node.tagName === 'img') {
        imageIndex += 1;
        const props = node.properties || (node.properties = {});
        const raw = typeof props.src === 'string' ? props.src.split(/[?#]/, 1)[0] : '';
        let key = raw;
        try { key = decodeURI(raw); } catch { /* retain original URL */ }
        const m = manifest[key] || manifest[raw];
        if (m) {
          if (props.width == null) props.width = m[0];
          if (props.height == null) props.height = m[1];
        }
        if (!props.decoding) props.decoding = 'async';
        // First image can be above the fold; do not lazy-load it by default.
        if (!props.loading && imageIndex > 1) props.loading = 'lazy';
      }
      if (Array.isArray(node.children)) for (const child of node.children) visit(child);
    }
    visit(tree);
  };
}
'''


def file_digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def usable_image(image: Image.Image) -> bool:
    if getattr(image, 'is_animated', False):
        return False
    return 0 < image.width * image.height <= 70_000_000


def webp_candidate(src: Path, dst: Path, quality: int, lossy: bool):
    try:
        with Image.open(src) as raw:
            if not usable_image(raw):
                return None, 'animated / huge image skipped'
            img = ImageOps.exif_transpose(raw)
            alpha = 'A' in img.getbands() or 'transparency' in img.info
            img = img.convert('RGBA' if alpha else 'RGB')
            dimensions = (img.width, img.height)
            dst.parent.mkdir(parents=True, exist_ok=True)
            # Lossless mode is pixel-exact. Lossy mode is explicit opt-in only.
            img.save(dst, 'WEBP', lossless=not lossy, quality=quality, method=6, exact=True)
            return dimensions, ''
    except Exception as err:
        try: dst.unlink(missing_ok=True)
        except Exception: pass
        return None, str(err)


def text_sources(root: Path) -> dict[Path, str]:
    base = root / 'src'
    if not base.exists():
        return {}
    sources = {}
    for path in base.rglob('*'):
        # Old unused source tree src/src is intentionally excluded.
        if path.relative_to(base).parts[0] == 'src':
            continue
        if path.is_file() and path.suffix.lower() in SOURCE_EXTS and 'node_modules' not in path.parts:
            try: sources[path] = path.read_text(encoding='utf-8')
            except (UnicodeDecodeError, OSError): continue
    return sources


def relpublic(public_file: Path, root: Path) -> str:
    return '/' + public_file.relative_to(root / 'public').as_posix()


def is_used(path: str, sources: dict[Path, str]) -> bool:
    # Explicit local path makes this match insensitive to cross-language references.
    return any(path in t or quote(path, safe='/') in t for t in sources.values())


def replace_public_paths(body: str, mapping: dict[str, str]) -> str:
    # Exclude partial-name matching, e.g. image-1.png versus image-10.png.
    for old, new in sorted(mapping.items(), key=lambda kv: len(kv[0]), reverse=True):
        body = re.sub(re.escape(old) + r'(?=$|[^\w.\-])', lambda _: new, body)
        escaped_old = quote(old, safe='/')
        if escaped_old != old:
            escaped_new = quote(new, safe='/')
            body = re.sub(re.escape(escaped_old) + r'(?=$|[^\w.\-])', lambda _: escaped_new, body)
    return body


def astro_config_patch(text: str) -> str:
    if 'rehype-embeddednote-images.mjs' in text:
        return text
    if re.search(r'\bmarkdown\s*:', text):
        raise ValueError('astro.config.mjs 已经自定义 markdown 配置，停止自动修改，避免覆盖现有插件。')
    # We verified this shape in the target EmbeddedNote repository.
    anchor = "import sitemap from '@astrojs/sitemap';"
    integration = 'integrations: [sitemap()],'
    if text.count(anchor) != 1 or text.count(integration) != 1:
        raise ValueError('astro.config.mjs 结构和已检查版本不同，安全停止：请核对配置。')
    text = text.replace(anchor, anchor + "\nimport embeddednoteImages from './scripts/rehype-embeddednote-images.mjs';")
    text = text.replace(integration, integration + "\n  markdown: { rehypePlugins: [embeddednoteImages] },")
    return text


def search_box_patch(text: str) -> str:
    if 'data-placeholder={placeholder}' not in text:
        raise ValueError('SearchBox.astro 搜索输入组件已变化，未进行CLS优化。')
    if 'min-height:76px' in text or 'min-height: 76px' in text:
        return text
    before = '<div id="search" data-placeholder={placeholder}></div>'
    after = '<div id="search" data-placeholder={placeholder} style="min-height:76px"></div>'
    if text.count(before) != 1:
        raise ValueError('SearchBox.astro 与已检查版本不匹配，未进行CLS优化。')
    return text.replace(before, after)


def build_report(work: Path, rows, touched_paths, expected_bytes, opts, total_sources, image_count):
    def kb(n): return f'{n/1024:,.0f} KiB'
    savings = sum(x['original_size'] - x['optimized_size'] for x in rows if x['selected'])
    selected = sum(x['selected'] for x in rows)
    data = [
        '<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"/>',
        '<meta name="viewport" content="width=device-width,initial-scale=1"/>',
        '<title>EmbeddedNote 图片优化预览报告</title>',
        '<style>body{font:15px/1.6 system-ui,"Microsoft YaHei",sans-serif;color:#17211e;max-width:1280px;margin:25px auto;padding:0 20px;background:#faf9f6}h1{font-size:26px}summary{cursor:pointer}small{color:#58605d}.grid{display:grid;grid-template-columns:1fr 1fr;gap:12px}.preview{width:100%;max-height:360px;object-fit:contain;background:#eee;border:1px solid #ddd}.item{background:white;border:1px solid #dedbd3;border-radius:10px;padding:16px;margin:15px 0;overflow-wrap:anywhere}.okay{color:#137844}.warn{color:#be5f26}.meta{font-family:Consolas,monospace;font-size:12px}.note{padding:12px;background:#fff6e6;border-left:3px solid #cf8d22}@media(max-width:680px){.grid{grid-template-columns:1fr}}</style></head><body>',
        '<h1>EmbeddedNote 图片压缩预览报告</h1>',
        f'<p>扫描文章与组件文件：{total_sources}个；识别到静态资源：{image_count}个；可无损优化：<b>{selected}个</b>；预计节省 <b>{kb(savings)}</b>（未经过在线压缩、网络缓存的传输量）。</p>',
        '<p class="note">默认使用无损WebP。图片像素不会被有损重编码；原始PNG/JPEG文件保留。以下左右图可点击放大。实际 Lighthouse 分数仍需上线后重新测量。</p>',
        f'<p>处理模式：<b>{"有损高质量（手动确认后采用）" if opts.lossy else "严格无损（推荐）"}</b>；优化比例阈值 {opts.min_saving:.0%}。由于资源必须比原图小才切换，跳过项是正常的。</p>',
        '<h2>改动文件预览</h2><details><summary>查看会修改的文本文件</summary><pre>'+html.escape('\n'.join(touched_paths))+'</pre></details>',
        '<h2>图片详情</h2>'
    ]
    for x in rows:
        label = '准备优化' if x['selected'] else '保持原图'
        state = 'okay' if x['selected'] else 'warn'
        original_url = x['source'].as_uri()
        candidate_url = x['preview'].as_uri() if x['preview'].exists() else original_url
        data.append('<div class="item">')
        data.append(f'<b class="{state}">{label}</b> &nbsp; <code>{html.escape(x["old_path"])}</code>')
        data.append(f'<p class="meta">原文件 {kb(x["original_size"])} | 候选 {kb(x["optimized_size"])} | 尺寸 {x["width"]}×{x["height"]} | {html.escape(x.get("note", ""))}</p>')
        data.append('<div class="grid">')
        data.append(f'<div><small>原图（点击查看）</small><a href="{html.escape(original_url,quote=True)}" target="_blank"><img class="preview" loading="lazy" src="{html.escape(original_url,quote=True)}"/></a></div>')
        data.append(f'<div><small>优化候选（点击查看）</small><a href="{html.escape(candidate_url,quote=True)}" target="_blank"><img class="preview" loading="lazy" src="{html.escape(candidate_url,quote=True)}"/></a></div>')
        data.append('</div></div>')
    data.append('</body></html>')
    report = work / 'image-review.html'
    report.write_text('\n'.join(data), encoding='utf-8')
    return report, savings, selected


def main():
    parser = argparse.ArgumentParser(description='EmbeddedNote 全站静态图片/首屏安全性能优化')
    parser.add_argument('--apply', action='store_true', help='预览核对无误后执行')
    parser.add_argument('--lossy', action='store_true', help='允许有损 WebP 编码（技术原理图不推荐；需严格人工核对）')
    parser.add_argument('--quality', type=int, default=93, help='--lossy 模式质量，默认93')
    parser.add_argument('--min-saving', type=float, default=0.08, help='图片须至少节省的比例，默认0.08')
    parser.add_argument('--skip-search-reserve', action='store_true', help='不尝试为首页搜索框预留空间')
    parser.add_argument('--no-astro-patch', action='store_true', help='仅处理图片引用，不安装全局Markdown图片属性插件')
    opts = parser.parse_args()
    if not (70 <= opts.quality <= 100): parser.error('--quality 必须在70～100之间')
    if not (0 <= opts.min_saving < 0.9): parser.error('--min-saving 取值必须为0～0.9')
    root = Path.cwd().resolve()
    if not (root/'package.json').is_file() or not (root/'astro.config.mjs').is_file() or not (root/'src/content/articles').is_dir() or not (root/'.git').exists():
        parser.error('请在 GitHub Desktop 的 embeddednote-website 仓库根目录运行（与 package.json 同级）。')
    work = root/'.git'/'embeddednote-performance'
    work.mkdir(parents=True,exist_ok=True)
    sources = text_sources(root)
    candidates = []
    manifest: dict[str, list[int]] = {}
    public_dir=root/'public'
    assets = sorted(p for base in [public_dir/'uploads',public_dir/'images'] if base.exists() for p in base.rglob('*') if p.is_file() and p.suffix.lower() in IMAGE_EXTS)
    for asset_no, src in enumerate(assets, 1):
        if asset_no % 20 == 0: print(f'正在分析图片 {asset_no}/{len(assets)} ...', flush=True)
        old=relpublic(src,root)
        if not is_used(old,sources): continue
        try:
            with Image.open(src) as image:
                if not usable_image(image): continue
                w,h=image.size
        except Exception as e:
            print(f'WARN 无法读取图片：{src.name}: {e}')
            continue
        manifest[old]=[w,h]
        size=src.stat().st_size
        candidate_rel=src.relative_to(public_dir).with_suffix('.webp')
        dest=public_dir/candidate_rel
        preview=work/'optimized'/candidate_rel
        note=''
        if dest.exists():
            note='目标WebP已存在，保护原文件、不覆盖'
            ok=False; preview=dest; optsize=dest.stat().st_size
        else:
            dims, err=webp_candidate(src,preview,opts.quality,opts.lossy)
            if err or not dims:
                note='压缩失败：'+err
                ok=False; optsize=size
            else:
                optsize=preview.stat().st_size
                ok=opts.min_saving <= (size-optsize)/size and optsize < size
                if not ok: note='压缩收益不足，保持原文件'
        new='/' + candidate_rel.as_posix()
        if ok: manifest[new]=[w,h]
        candidates.append({'source':src,'old_path':old,'new_path':new,'dest':dest,'preview':preview,'original_size':size,'optimized_size':optsize,'selected':ok,'width':w,'height':h,'note':note})
    # Preserve dimensions across repeated runs: include already-optimized WebP/AVIF
    # images, not only the source PNG/JPEG candidates. This makes --apply idempotent.
    for base in [public_dir/'uploads', public_dir/'images']:
        if not base.exists(): continue
        for src in base.rglob('*'):
            if not src.is_file() or src.suffix.lower() not in {'.webp', '.avif', '.gif'}:
                continue
            url = relpublic(src, root)
            if not is_used(url, sources): continue
            try:
                with Image.open(src) as img:
                    if usable_image(img): manifest[url] = [img.width, img.height]
            except (OSError, ValueError): pass
    mapping={r['old_path']:r['new_path'] for r in candidates if r['selected']}
    changed={}
    for src,body in sources.items():
        # Only known referenced image URLs are changed; article words/metadata remain unchanged.
        next_body=replace_public_paths(body,mapping)
        if next_body!=body: changed[src]=next_body
    config=root/'astro.config.mjs'
    plugin=root/PLUGIN_REL
    json_file=root/MANIFEST_REL
    if not opts.no_astro_patch:
        patched=astro_config_patch(config.read_text(encoding='utf-8'))
        if patched != config.read_text(encoding='utf-8'): changed[config]=patched
        if plugin.exists() and plugin.read_text(encoding='utf-8')!=IMAGE_PLUGIN:
            print('ERROR：插件文件已存在且内容与脚本版本不同，停止以避免覆盖人工修改。')
            sys.exit(3)
    search=root/'src/components/SearchBox.astro'
    if not opts.skip_search_reserve and search.exists():
        current=changed.get(search, search.read_text(encoding='utf-8'))
        patched=search_box_patch(current)
        if patched!=current:changed[search]=patched
    all_paths=sorted(str(p.relative_to(root)) for p in changed)
    if not opts.no_astro_patch:
        all_paths += [str(PLUGIN_REL),str(MANIFEST_REL)]
    report,savings,selected=build_report(work,candidates,all_paths,0,opts,len(sources),len(assets))
    print(f'{"APPLY" if opts.apply else "PREVIEW"} | 检查源码文件 {len(sources)} 个；候选图片 {len(candidates)} 张')
    print(f'符合压缩阈值的图片：{selected} 张；预计节省 {savings/1024:.0f} KiB（源文件仍保留）')
    print(f'需要修改的已有文本文件：{len(changed)} 个')
    print(f'图片对照报告：{report}')
    if not opts.apply:
        print('预览模式未修改网站内容。浏览报告核实后执行：py .\\optimize_embeddednote_site.py --apply')
        return
    timestamp=dt.datetime.now().strftime('%Y%m%d-%H%M%S')
    backup=work/'backups'/timestamp
    for path in changed:
        dest=backup/path.relative_to(root)
        dest.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(path,dest)
    if plugin.exists():
        dest=backup/PLUGIN_REL;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(plugin,dest)
    if json_file.exists():
        dest=backup/MANIFEST_REL;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(json_file,dest)
    # Write binary conversions first; originals remain intact for safe rollback.
    for row in candidates:
        if not row['selected']:continue
        row['dest'].parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(row['preview'],row['dest'])
    for path,body in changed.items():
        path.write_text(body,encoding='utf-8',newline='')
    if not opts.no_astro_patch:
        plugin.parent.mkdir(parents=True,exist_ok=True)
        plugin.write_text(IMAGE_PLUGIN,encoding='utf-8')
        json_file.parent.mkdir(parents=True,exist_ok=True)
        json_file.write_text(json.dumps(manifest,ensure_ascii=False,indent=2,sort_keys=True)+'\n',encoding='utf-8')
    result={'created':dt.datetime.now().isoformat(),'images_converted':selected,'bytes_saved':savings,'files_modified':[str(p.relative_to(root)) for p in changed],'files_created':[str(row['dest'].relative_to(root)) for row in candidates if row['selected']]+([] if opts.no_astro_patch else [str(PLUGIN_REL),str(MANIFEST_REL)]),'backup':str(backup)}
    (work/'last-apply.json').write_text(json.dumps(result,indent=2,ensure_ascii=False),encoding='utf-8')
    print('DONE. 已修改文件；已备份到：',backup)
    print('请执行：npm run build ；确认 GitHub Desktop Changes 后 Commit / Push，再用 PageSpeed 复测。')
    print('勿提交此Python脚本和 .git 中的预览/备份；保留原始图片以便回退。')

if __name__=='__main__':
    try:main()
    except (OSError,ValueError) as exc:
        print('安全停止，未完成该操作：'+str(exc),file=sys.stderr)
        sys.exit(1)
